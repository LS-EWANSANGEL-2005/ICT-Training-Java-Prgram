package ICTjavaProgram;

public class TypeCasting {

    public static void main(String[] args) {

        int a = 100;
        double d1 = a;

        System.out.println("Int to Double: " + d1);

        double d = 123.78;
        int b = (int) d;

        System.out.println("Double to Int: " + b);

        int num = 130;
        byte c = (byte) num;

        System.out.println("Int to Byte: " + c);
    }
}



